function getTopics(tab: TabId): Topic[] {
  if (tab === "protection") return protectionTopics
  if (tab === "saving") return savingTopics
  if (tab === "life") return lifeTopics
  if (tab === "liability") return liabilityTopics
  if (tab === "prenatal") return prenatalTopics
  if (tab === "pet") return petTopics
  if (tab === "municipal") return municipalTopics
  if (tab === "joint") return jointTopics
  if (tab === "dental") return dentalTopics
  return protectionTopics
}

function findTabByTopic(id: string): TabId {
  if (savingTopics.some((topic) => topic.id === id)) return "saving"
  if (lifeTopics.some((topic) => topic.id === id)) return "life"
  if (liabilityTopics.some((topic) => topic.id === id)) return "liability"
  if (prenatalTopics.some((topic) => topic.id === id)) return "prenatal"
  if (petTopics.some((topic) => topic.id === id)) return "pet"
  if (municipalTopics.some((topic) => topic.id === id)) return "municipal"
  if (jointTopics.some((topic) => topic.id === id)) return "joint"
  if (dentalTopics.some((topic) => topic.id === id)) return "dental"
  return "protection"
}

function ListCard({ title, items }: { title: string; items: string[] }) {
  return (
    <InfoCard title={title}>
      <div className="grid gap-2">
        {items.map((item, index) => (
          <div key={item} className="flex gap-3 rounded-xl bg-slate-50 px-4 py-3">
            <span className="grid h-7 w-7 shrink-0 place-items-center rounded-full bg-white text-[12px] font-black text-[#2563eb] shadow-sm">{index + 1}</span>
            <span className="min-w-0 text-[14px] font-bold leading-7 text-slate-700">{item}</span>
          </div>
        ))}
      </div>
    </InfoCard>
  )
}

function InfoCard({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="rounded-2xl border border-slate-200 bg-white p-5 shadow-sm [overflow-wrap:anywhere] [text-wrap:pretty] [word-break:keep-all] md:p-6">
      <h2 className="mb-4 text-xl font-black text-[#12325f]">{title}</h2>
      {children}
    </section>
  )
}
